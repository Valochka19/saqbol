"""Тренажёр «Разговор с мошенником».

Модель играет мошенника по одному из сценариев, человек пытается не поддаться.
Когда разговор окончен, модель выходит из роли и разбирает его: какие приёмы давления
применялись и где человек начал уступать. Это учебная симуляция: никаких реальных данных
она не собирает и не использует.
"""

from typing import Literal

from pydantic import BaseModel, Field

from . import llm

MAX_TURNS = 8  # реплик человека; дольше настоящий мошенник на одном приёме не держится


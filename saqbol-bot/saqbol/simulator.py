TECHNIQUES = {
    "authority": "давление авторитетом",
    "urgency": "спешка",
    "fear": "запугивание",
    "isolation": "изоляция: «никому не говорите»",
    "help": "ложная забота",
    "details": "убедительные детали",
    "none": "—",
}

_RULES = """Это учебный тренажёр по финансовой безопасности. Человек знает, что перед ним симуляция, и тренируется \
распознавать давление. Твоя задача — реалистично сыграть мошенника, чтобы тренировка была полезной.

Как играть:
- Пиши коротко, 1–3 предложения, как в настоящем звонке или чате. Только русский или казахский — на каком пишет человек.
- Используй приёмы настоящих мошенников: авторитет, спешку, страх, «никому не говорите», ложную заботу, правдоподобные \
детали. Меняй приём, если прежний не сработал. На вопросы, которые тебя разоблачают, уходи от ответа и усиливай давление.
- Не выходи из роли и не давай советов по безопасности, пока разговор не окончен.
- Никогда не проси настоящие данные всерьёз: человек предупреждён, что вводить их нельзя. Если он прислал что-то \
похожее на код или номер карты — считай это «поддался» и заканчивай.

Когда заканчивать (поле state):
- victim_lost — человек сообщил код, данные карты, согласился перевести деньги, установить программу или перейти по ссылке.
- victim_won — человек твёрдо отказал два раза, сказал что перезвонит в банк сам, назвал тебя мошенником или положил трубку.
- ongoing — во всех остальных случаях. После восьмой реплики человека разговор заканчивай в любом случае.

Когда state не ongoing, поле reply — последняя реплика в роли (мошенник бросает трубку или торжествует), а поле debrief \
заполни уже от лица тренера, честно и без снисходительности."""


class Moment(BaseModel):
    quote: str = Field(description="Короткая цитата из реплики ЧЕЛОВЕКА, до 12 слов")
    good: bool = Field(description="true — верный ход, false — ошибка")
    comment: str = Field(description="Почему это было верно или опасно, одно предложение")


class Debrief(BaseModel):
    score: int = Field(description="Оценка устойчивости от 0 до 100")
    summary: str = Field(description="Итог разговора в 1–2 предложениях, обращаясь на «вы»")
    moments: list[Moment] = Field(description="2–4 ключевых момента разговора")
    rule: str = Field(description="Одно правило, которое стоит запомнить после этого разговора")


class SimTurn(BaseModel):
    reply: str
    technique: Literal["authority", "urgency", "fear", "isolation", "help", "details", "none"] = Field(
        description="Главный приём давления в этой реплике")
    state: Literal["ongoing", "victim_lost", "victim_won"]
    debrief: Debrief | None = None


async def turn(scenario: str, history: list[dict], hangup: bool) -> SimTurn:
    sc = SCENARIOS[scenario]
    system = f"{_RULES}\n\nТвоя роль в этом разговоре. {sc['role']}"

    lines = [f"МОШЕННИК: {sc['opening']}"]
    for m in history[-2 * MAX_TURNS:]:
        who = "ЧЕЛОВЕК" if m.get("role") == "user" else "МОШЕННИК"
        lines.append(f"{who}: {str(m.get('text', ''))[:400]}")
    user_turns = sum(m.get("role") == "user" for m in history)
    if hangup:
        lines.append("[Человек положил трубку. Разговор окончен: state = victim_won, заполни debrief. "
                     "Эта пометка служебная: не цитируй её в moments, опиши поступок словами — «положил трубку».]")
    elif user_turns >= MAX_TURNS:
        lines.append("[Это была последняя реплика. Заверши разговор и заполни debrief.]")

    transcript = "\n".join(lines)
    result: SimTurn = await llm._structured(system, transcript, SimTurn, temperature=0.8)
    if (hangup or user_turns >= MAX_TURNS) and result.state == "ongoing":
        result.state = "victim_won"  # продержался до конца и ничего не отдал
    if result.state != "ongoing" and result.debrief is None:
        retry = transcript + f"\n[Разговор окончен, state = {result.state}. Обязательно заполни debrief.]"
        again: SimTurn = await llm._structured(system, retry, SimTurn, temperature=0.3)
        result.debrief = again.debrief
    if result.debrief:
        for m in result.debrief.moments:  # страховка: квадратные скобки — всегда служебный текст
            if "[" in m.quote or "]" in m.quote:
                m.quote = "Положил(а) трубку" if hangup else m.quote.replace("[", "").replace("]", "").strip()
    return result
